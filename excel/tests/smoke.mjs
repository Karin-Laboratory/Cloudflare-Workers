import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
const app=readFileSync(new URL("../app.txt",import.meta.url),"utf8");
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const worker=readFileSync(new URL("../worker.js",import.meta.url),"utf8");
assert.match(app,/window\.x_spreadsheet\("#spreadsheet"/,"Spreadsheet must call the x_spreadsheet browser global");
assert.doesNotMatch(app,/window\.x\.spreadsheet/,"Do not use a nonexistent browser global");
assert.doesNotMatch(app,/if\(!window\.x\|\|!window\.XLSX\)/,"Missing SheetJS must not prevent editor startup");
for(const path of ["/vendor/xspreadsheet.js","/vendor/xspreadsheet.css","/vendor/xlsx.full.min.js"]){
  assert.ok(html.includes(path),"Missing same-origin vendor link: "+path);
  assert.ok(worker.includes('"' +path+ '"'),"Missing Worker vendor route: "+path);
}
assert.match(worker,/if\(Object\.prototype\.hasOwnProperty\.call\(vendors,url\.pathname\)\)return vendor\(req,url\.pathname\)/,"Vendor requests must be served by Worker");
import { statSync } from "node:fs";
const size=statSync(new URL("../public/vendor/xlsx.full.min.js",import.meta.url)).size;
assert.ok(size > 300_000, "Locally bundled SheetJS file must exist");
import * as XLSX from "xlsx";
assert.match(app,/const created=await api\("\/api\/books","POST",\{name,data\}\)/, "File open must create new cloud workbook");
assert.doesNotMatch(app,/内容を読み込み結果で置き換えます/, "File open must never replace active workbook");
const fromStart=app.indexOf("function fromXlsx(wb){");
const fromEnd=app.indexOf("function toXlsx(){",fromStart);
assert.ok(fromStart>-1 && fromEnd>fromStart,"XLSX converter must exist");
const fromXlsx=new Function("XLSX",app.slice(fromStart,fromEnd)+";return fromXlsx;")(XLSX);
const sample=XLSX.utils.book_new();
const sheet=XLSX.utils.aoa_to_sheet([["タイトル","著者"],["架空の書籍","山田太郎"],[120,45]]);
sheet.B4={t:"n",f:"SUM(A3:B3)",v:165};
sheet["!ref"]="A1:B4";
XLSX.utils.book_append_sheet(sample,sheet,"書籍");
const generated=XLSX.write(sample,{bookType:"xlsx",type:"buffer"});
const parsed=XLSX.read(generated,{type:"buffer",cellFormula:true});
const restored=fromXlsx(parsed);
assert.equal(restored[0].name,"書籍");
assert.equal(restored[0].rows.cells[1].cells[0].text,"架空の書籍");
assert.equal(restored[0].rows.cells[1].cells[1].text,"山田太郎");
assert.equal(restored[0].rows.cells[3].cells[1].text,"=SUM(A3:B3)");
console.log("Karin Excel smoke checks passed; SheetJS bytes:",size,"; XLSX roundtrip verified");
